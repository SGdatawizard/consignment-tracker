function daysAgo(n) {
  const d = new Date()
  d.setDate(d.getDate() - n)
  return d.toISOString().slice(0, 10)
}

function hoursAgo(n) {
  return new Date(Date.now() - n * 3600 * 1000).toISOString()
}

